/**
 * Ventana Celeste — service worker.
 *
 * What it is for, in one line: the app has to open and the sky has to draw with
 * the phone in flight mode, on a hill, with no signal.
 *
 * It replaces a pass-through worker that existed only to make Chrome offer the
 * install prompt. That one answered every request with `fetch()`, which is the
 * same as having no worker at all — the app installed, and then opened to a
 * blank canvas the moment the network went away.
 *
 * Two caches, kept apart on purpose:
 *
 *   SHELL — the app itself. Small, replaced wholesale on every deploy, so it is
 *   versioned and the old one is thrown away when a new worker activates.
 *
 *   DATA  — the sky: stars, planets, survey tiles. Tens of gigabytes, put there
 *   deliberately by the user through the download panel, and NEVER cleaned up
 *   automatically. Deleting somebody's 27 GB because the app was rebuilt would
 *   be unforgivable, so no activate handler is allowed near it.
 */

const SHELL = "vc-shell-v5";
const DATA = "vc-data-v1";

// The navigation entry. Everything else comes from precache.json, which the
// build writes from the files it actually produced.
const SHELL_SEED = ["./"];

const DATA_HOSTS = ["smalldata.ventanaceleste.com", "bigdata.ventanaceleste.com"];

// Opened once, not once per request. Every tile the engine draws comes through
// the fetch handler, and at Norder6 that is tens of thousands of them.
let dataCache = null;
function openData() {
  if (!dataCache) dataCache = caches.open(DATA);
  return dataCache;
}

/**
 * Install: take the WHOLE shell, or take none of it.
 *
 * This used to seed eight hand-written paths and leave the fingerprinted
 * bundles to be picked up later, "on the first online visit". That leaves a
 * window with no way out of it: a new worker creates its cache, activation
 * deletes the old one, and until the app is next opened WITH A CONNECTION the
 * only thing cached is a document naming a bundle that is not there. Open it in
 * flight mode inside that window and the screen is white - not a broken sky, no
 * app at all. Opening it once on wifi filled the cache and it never happened
 * again, which is exactly what makes it so easy to dismiss.
 *
 * So the list is generated by the build, and addAll is deliberate: it is atomic,
 * so a half-downloaded shell is never installed. If it fails, this worker simply
 * does not take over and the previous one - which still has a complete cache -
 * keeps serving. The update waits for a better moment instead of breaking now.
 */
self.addEventListener("install", (e) => {
  e.waitUntil(
    (async () => {
      const cache = await caches.open(SHELL);
      let list = [];
      try {
        const res = await fetch("./precache.json", { cache: "no-store" });
        if (res.ok) list = (await res.json()).files || [];
      } catch (err) {
        // no manifest: fall through to the navigation entry alone rather than
        // failing the install outright
      }
      const wanted = Array.from(new Set([...SHELL_SEED, ...list]));
      await cache.addAll(wanted);
      await self.skipWaiting();
    })()
  );
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        // only ever old SHELL versions. DATA is the user's, and is not ours to bin.
        keys.filter((k) => k.startsWith("vc-shell-") && k !== SHELL)
            .map((k) => caches.delete(k))
      )
    ).then(() => self.clients.claim())
  );
});

function isData(url) {
  return DATA_HOSTS.includes(url.hostname) && !url.pathname.startsWith("/bundle");
}

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;

  let url;
  try {
    url = new URL(req.url);
  } catch {
    return;
  }

  // The bundler is how data GETS into the cache; it must never be served out of
  // it, or a re-download would hand back what it is trying to replace.
  if (url.pathname.startsWith("/bundle")) return;

  if (isData(url)) {
    // Cache first, and the miss goes to the network without being cached: what
    // is offline is exactly what the user asked to have offline, so the cache
    // stays a thing they chose rather than a thing that grew.
    // NEVER ignoreSearch here.
    //
    // It reads like a harmless bit of tolerance and it is the most expensive
    // line in the app. An exact match is an index lookup and is flat: 0.2 ms
    // whether the cache holds two thousand entries or thirty thousand. With
    // ignoreSearch the cache cannot use the index at all - it walks the entries
    // and compares them one by one - so the cost grows with everything the user
    // has ever downloaded. Measured, on a desktop:
    //
    //     2,000 entries   0.08 ms exact    2.8 ms ignoreSearch
    //    10,000 entries   0.24 ms exact   12.5 ms ignoreSearch
    //    30,000 entries   0.17 ms exact   42.7 ms ignoreSearch
    //
    // The sky is hundreds of tiles. At Norder6 - 49,152 of them - that is a
    // black canvas for minutes on a phone, and it got worse with every source
    // downloaded, which is precisely backwards from what a download is for.
    //
    // Query strings are still tolerated, by a SECOND exact lookup on the bare
    // path rather than by a scan. Two index hits are still flat.
    e.respondWith(
      openData().then((c) =>
        c
          .match(req)
          .then((hit) => hit || (url.search ? c.match(url.origin + url.pathname) : null))
          .then((hit) => hit || fetch(req))
      )
    );
    return;
  }

  if (url.origin !== self.location.origin) return;

  // The DOCUMENT is network-first, and this is not a preference.
  //
  // Vite fingerprints the bundles, so index.html names files like
  // index-C5CwMp60.js. Serve a cached index.html after a deploy and it asks for
  // a hash that is no longer on the server: the host answers the SPA fallback,
  // the browser gets text/html where it wanted a module, and the app does not
  // start. It came back the second time, once the background refresh had landed
  // — which is a bug that only ever bites the first person to open it after a
  // release, and looks like nothing at all when you reload.
  //
  // So: ask the network, fall back to the cache. The document is a kilobyte, and
  // with no network the cached one is still exactly right.
  if (req.mode === "navigate" || (req.headers.get("accept") || "").includes("text/html")) {
    e.respondWith(
      fetch(req)
        .then(async (res) => {
          if (res && res.ok) {
            const copy = res.clone();
            caches.open(SHELL).then((c) => c.put(req, copy));
            return res;
          }
          // Not every failure is a clean one. Flight mode makes fetch reject and
          // the catch below handles it, but a captive portal, a proxy or a
          // server having a bad morning answers with a 502 or a login page - a
          // perfectly successful fetch of the wrong thing. Handing that to the
          // browser replaces a working offline app with an error page, so the
          // cached document wins whenever the network does not actually deliver.
          const c = await caches.open(SHELL);
          return (await c.match("./index.html")) || (await c.match("./")) || res;
        })
        // `hit || c.match(...)` was wrong in a way that only shows with no
        // network: c.match returns a PROMISE, and a promise is always truthy,
        // so the last fallback could never run and a miss resolved to undefined
        // - which respondWith turns into a network error, and a white page.
        .catch(async () => {
          const c = await caches.open(SHELL);
          return (
            (await c.match(req)) ||
            (await c.match("./index.html")) ||
            (await c.match("./")) ||
            Response.error()
          );
        })
    );
    return;
  }

  // Everything else the app is made of - the fingerprinted bundles, the wasm,
  // the icons - is immutable under its own name, so the cache is always right
  // and the background refresh is only there to pick up anything unhashed.
  e.respondWith(
    caches.open(SHELL).then((c) =>
      c.match(req).then((hit) => {
        const net = fetch(req)
          .then((res) => {
            if (res && res.ok && res.type === "basic") c.put(req, res.clone());
            return res;
          })
          .catch(() => hit);
        return hit || net;
      })
    )
  );
});

// The download panel asks how much is actually there, and asks for a tile to be
// dropped again. It talks through here rather than opening the caches itself so
// there is one place that knows what the cache is called.
self.addEventListener("message", (e) => {
  const msg = e.data || {};
  if (msg.type === "vc-data-cache-name") {
    e.ports[0] && e.ports[0].postMessage({ name: DATA });
  }
});
